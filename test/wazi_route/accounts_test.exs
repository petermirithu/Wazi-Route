  describe "email verification OTP" do
    setup do
      %{user: unconfirmed_user_fixture()}
    end

    test "delivers a branded six-digit code and verifies the user", %{user: user} do
      {:ok, job} =
        Accounts.deliver_email_verification_code(user, "https://example.com/users/verify-email")

      code = verification_code(job)
      assert code =~ ~r/^\d{6}$/
      assert mail_arg(job, :html_body) =~ code
      assert mail_arg(job, :html_body) =~ "WAZI"

      assert {:ok, verified_user} = Accounts.verify_user_email_otp(user, code)
      assert verified_user.confirmed_at
      assert Accounts.get_user_by_email_and_password(user.email, valid_user_password())
      refute Repo.get_by(UserToken, user_id: user.id, context: "verify_email")
    end

    test "limits invalid code attempts to five", %{user: user} do
      {:ok, job} =
        Accounts.deliver_email_verification_code(user, "https://example.com/users/verify-email")

      wrong_code = if verification_code(job) == "000000", do: "111111", else: "000000"

      for remaining <- 4..0//-1 do
        assert {:error, {:invalid_code, ^remaining}} =
                 Accounts.verify_user_email_otp(user, wrong_code)
      end

      assert {:error, :locked} = Accounts.verify_user_email_otp(user, wrong_code)
      refute Accounts.get_user!(user.id).confirmed_at
    end

    test "rejects an expired code", %{user: user} do
      {:ok, job} =
        Accounts.deliver_email_verification_code(user, "https://example.com/users/verify-email")

      code = verification_code(job)
      expired_at = DateTime.utc_now(:second) |> DateTime.add(-11, :minute)
      Repo.update_all(UserToken, set: [inserted_at: expired_at])

      assert {:error, :expired} = Accounts.verify_user_email_otp(user, code)
    end

    test "enforces the resend cooldown", %{user: user} do
      verification_url = "https://example.com/users/verify-email"
      assert {:ok, _job} = Accounts.deliver_email_verification_code(user, verification_url)

      assert {:error, :too_soon} =
               Accounts.deliver_email_verification_code(user, verification_url)

      available_at = DateTime.utc_now(:second) |> DateTime.add(-61, :second)
      Repo.update_all(UserToken, set: [inserted_at: available_at])

      assert {:ok, _job} = Accounts.deliver_email_verification_code(user, verification_url)
    end
  end

  describe "inspect/2 for the User module" do
    test "does not include password" do
      refute inspect(%User{password: "123456"}) =~ "password: \"123456\""
    end
  end

  defp verification_code(job) do
    [_, code] = Regex.run(~r/verification code is:\s+(\d{6})/i, mail_arg(job, :text_body))
    code
  end

  defp mail_arg(%Oban.Job{args: args}, key) do
    Map.get(args, key) || Map.fetch!(args, Atom.to_string(key))
  end
end
